const translations: Record<ProductLanguage, Partial<Record<MyMonitorTranslationKey, string>>> = { en, ko };

export function resolveLocalizedValue(
  language: string | null | undefined,
  englishValue: string,
  localizedValue?: string,
): string {
  return normalizeProductLanguage(language) === FALLBACK_PRODUCT_LANGUAGE
    ? englishValue
    : localizedValue ?? englishValue;
}

export function translateMyMonitor(
  key: MyMonitorTranslationKey,
  language: string | null | undefined,
): string {
  const normalized = normalizeProductLanguage(language);
  const englishValue = en[key];
  return resolveLocalizedValue(
    normalized,
    englishValue,
    normalized ? translations[normalized]?.[key] : undefined,
  );
}
